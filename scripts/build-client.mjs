import { readFile, writeFile } from "node:fs/promises";
import { Script, runInNewContext } from "node:vm";

const root = new URL("../client/", import.meta.url);
const sources = await Promise.all(["dream.js", "recall.js"].map((name) => readFile(new URL(name, root), "utf8")));
const modules = sources.map((source) => {
  let registration;
  runInNewContext(source, { window: { __ModuleLoader__: { load(value) { registration = value; } } } });
  if (typeof registration?.factory !== "function") throw new Error("Client source must register one factory");
  return registration;
});
const [dream, recall] = modules;
const call = 'require("dsh-recall-dream").install(ctx, mount)';
const factory = recall.factory.toString();
if (!factory.includes(call)) throw new Error("Recall entry must install the Dream UI");
const combined = factory.replace(call, `(${dream.factory.toString()})(require).install(ctx, mount)`);
const bundle = `// Generated by scripts/build-client.mjs; edit dream.js or recall.js.\nwindow.__ModuleLoader__.load({ id: ${JSON.stringify(recall.id)}, factory: ${combined} });\n`;
new Script(bundle, { filename: "dsh-recall/client/client.js" });
await writeFile(new URL("client.js", root), bundle);
